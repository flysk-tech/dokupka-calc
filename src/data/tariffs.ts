/* Тариф: price — за пользователя в месяц; для пакетов base — цена пакета в месяц, included — сколько
   пользователей входит, price — цена каждого сверх пакета (null — докупить нельзя), yearly — годовой пакет. */
const U = (g: string, name: string, price: number, from: string, to: string, o: Partial<Plan> = {}): Plan =>
  ({ g, name, price, base: 0, included: 0, minUsers: 1, maxUsers: Infinity, from, to, ...o })
const PKG = (g: string, name: string, base: number, users: number, from: string, to: string, o: Partial<Plan> = {}): Plan => {
  const r: Plan = { g, name, price: null, base, included: users, minUsers: 1, maxUsers: users, from, to, ...o }
  if (r.price) r.maxUsers = Infinity
  return r
}
const YEAR = (g: string, name: string, priceYear: number, users: number, from: string, to: string, o: Partial<Plan> = {}): Plan =>
  PKG(g, name, priceYear / 12, users, from, to, { yearly: true, ...o })
